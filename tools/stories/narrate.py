"""Turn one Ampli Stories series (stories/<id>/) into narrated episodes.

For each NN.txt (line 1 = title, then the narration), synthesise speech with the
open-source Kokoro voice model (Apache-2.0, runs on the CI CPU, no API key, no cost),
encode to AAC .m4a and upload it to the GitHub release that hosts story audio.
Episodes whose text and voice have not changed are skipped (the file name carries a
hash), so re-running only narrates new or edited episodes.

Writes build/stories/<id>.json describing the series for make_catalog.py.

Usage: python narrate.py <series_dir> <release_tag> <repo>
"""
import hashlib, json, os, re, subprocess, sys
from pathlib import Path

VOICES = {"kids": "hm_omega", "fantasy": "hf_alpha", "horror": "hf_beta"}
DEFAULT_VOICE = "hf_alpha"
SPEED = 0.95
SR = 24000


def sh(*args, **kw):
    return subprocess.run(args, check=True, text=True, capture_output=True, **kw).stdout


def existing_assets(tag, repo):
    try:
        out = sh("gh", "release", "view", tag, "--repo", repo, "--json", "assets")
    except subprocess.CalledProcessError:
        sh("gh", "release", "create", tag, "--repo", repo, "--title", "Ampli Stories audio",
           "--notes", "Narrated episodes for the Stories tab. Generated by the Stories workflow.",
           "--prerelease")
        return set()
    return {a["name"] for a in json.loads(out)["assets"]}


def sentences(text):
    text = re.sub(r"\s+", " ", text).strip()
    parts = re.split(r"(?<=[।!?\.])\s+", text)
    out, buf = [], ""
    for p in parts:  # keep chunks a comfortable size for the model
        if len(buf) + len(p) < 220:
            buf = (buf + " " + p).strip()
        else:
            if buf:
                out.append(buf)
            buf = p
    if buf:
        out.append(buf)
    return out


def narrate(pipeline, voice, title, body, wav_path):
    import numpy as np, soundfile as sf
    pause = np.zeros(int(SR * 0.35), dtype=np.float32)
    chunks = []
    for line in [title] + sentences(body):
        for _, _, audio in pipeline(line, voice=voice, speed=SPEED):
            chunks.append(np.asarray(audio, dtype=np.float32))
        chunks.append(pause)
        if line is title:
            chunks.append(pause)
    audio = np.concatenate(chunks)
    sf.write(wav_path, audio, SR)
    return len(audio) / SR


def main():
    series_dir, tag, repo = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
    meta = json.loads((series_dir / "series.json").read_text(encoding="utf-8"))
    sid = meta["id"]
    voice = meta.get("voice") or VOICES.get(meta.get("genre"), DEFAULT_VOICE)
    have = existing_assets(tag, repo)
    out_dir = Path("build/stories"); out_dir.mkdir(parents=True, exist_ok=True)
    prev = {}
    prev_file = Path("docs/stories/catalog.json")
    if prev_file.exists():
        for s in json.loads(prev_file.read_text(encoding="utf-8")).get("series", []):
            if s["id"] == sid:
                prev = {e["file"]: e.get("durationSec", 0) for e in s["episodes"]}
    pipeline = None
    episodes = []
    for f in sorted(series_dir.glob("[0-9][0-9].txt")):
        raw = f.read_text(encoding="utf-8").strip().splitlines()
        title, body = raw[0].strip(), "\n".join(raw[1:]).strip()
        digest = hashlib.sha1(f"{voice}|{SPEED}|{title}|{body}".encode()).hexdigest()[:10]
        n = int(f.stem)
        name = f"{sid}-{n:02d}-{digest}.m4a"
        duration = prev.get(name, 0)
        if name not in have:
            if pipeline is None:
                from kokoro import KPipeline
                pipeline = KPipeline(lang_code="h")
            wav = out_dir / f"{sid}-{n:02d}.wav"
            duration = narrate(pipeline, voice, title, body, wav)
            m4a = out_dir / name
            sh("ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-ac", "1", "-c:a", "aac",
               "-b:a", "48k", "-movflags", "+faststart", str(m4a))
            sh("gh", "release", "upload", tag, str(m4a), "--repo", repo, "--clobber")
            wav.unlink(); m4a.unlink()
            print(f"narrated {name} ({duration:.0f}s)")
        else:
            print(f"kept {name}")
        episodes.append({"n": n, "title": title, "file": name,
                         "url": f"https://github.com/{repo}/releases/download/{tag}/{name}",
                         "durationSec": int(round(duration))})
    meta["voice"] = voice
    meta["episodes"] = episodes
    (out_dir / f"{sid}.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
